export const WRITING_RULES = `# 网文写作规范
1. 开门见山，直接进入场景和冲突，不要大段背景介绍和环境铺陈。
2. 每章至少一个明确的冲突或看点，有情绪起伏；爽点要有铺垫再释放（压抑→爆发、打脸、收获、反转）。
3. 章末留钩子：悬念、危机、反转或期待感，让读者想看下一章。
4. 展示而非说明：用动作、对话、细节和反应表现人物，不要直接下判断（如“他很愤怒”）。
5. 对话要符合人物身份和性格，推动剧情；配角有自己的动机，不是工具人。
6. 短段落，手机阅读友好；一段一般不超过 4 行，对话单独成段。
7. 严格遵守设定和人物当前状态，不能与前文矛盾（境界、伤势、所在地点、持有物品、已知信息、人物关系、生死）。人物只能知道自己“知道的秘密”里的事。
8. 避免 AI 腔：不要用“不禁”“仿佛”“心中一凛”“嘴角勾起一抹弧度”“空气仿佛凝固了”等套话；不要排比抒情；不要在结尾总结升华、说教或展望未来；不要写“本章完”。
9. 只推进本章大纲规定的剧情，不要擅自写到后面章节的内容，更不要让故事提前结束。`;

export function novelHeader(n: Novel): string {
  return `- 书名：${n.title}
- 类型：${n.genre}
- 核心灵感：${n.idea || "（未填写）"}
- 文风要求：${n.style || "流畅、有画面感、节奏明快"}
- 规划篇幅：约 ${n.targetChapters} 章，每章约 ${n.wordsPerChapter} 字`;
}

